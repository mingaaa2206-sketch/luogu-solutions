// 思路：把时间统一成“分钟”，从 8:00 往回倒推，全程整数运算。
#include <stdio.h>


int main(void)
{
    int s, v;
    if (scanf("%d %d", &s, &v) != 2)   /* s: 路程（米）  v: 速度（米/分钟） */
        return 0;
    int walk;
    //路上用时，向上取整：walk = ceil(s / v)
    if((s%v)!=0)
    walk=s/v+1;
    else
    walk=s/v;


    int need = walk + 10;


    /* 从当天 0 点算起的出发分钟数：8:00 = 8*60 = 480 分钟。
     * 480 - need 可能为负（说明要退到前一天出发）。
     */
    int t = 8 * 60 - need;


    /* 运算顺序：`*` 的优先级高于 `%=`，所以这一行等价于
     *     t = t % (24 * 60)     即   t = t % 1440;
     * 赋值运算符右结合、优先级只比逗号高，右侧整个 `24 * 60` 都是它的右操作数。
     * 不是 (t %= 24) * 60 —— 那种读法虽然也能编译（赋值的值就是刚赋进去的数），
     * 但结果完全不同：t 为 -9530 时，两种写法分别得到 -890 和 -120。
     */
    t %= 24 * 60;


    
    if (t < 0)
        t += 24 * 60;


    /* ---------- 输出 HH:MM ----------
     * %02d 是 printf 的格式说明符，拆开看：
     *   '%'  转换开始标记
     *   '0'  标志位：空白处用 0 填充（不写这个 0 则默认用空格填充）
     *   '2'  最小字段宽度 2 —— 是下限不是上限，所以 123 照样输出 123、不截断
     *   'd'  有符号十进制整数
     * 效果：7:48 输出成 07:48，23:50 原样输出；负号也算 1 个字符（如 %03d 的 -5 得 -05）。
     * 提醒：scanf 里的 %2d 含义完全不同，表示“最多读入 2 个字符”，
     *       %02d 写进 scanf 更是无效写法 —— printf 负责排版，scanf 只描述类型。
     */
    printf("%02d:%02d\n", t / 60, t % 60);


    return 0;
}
